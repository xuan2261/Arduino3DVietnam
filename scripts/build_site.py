"""Build a portable static site using only Python standard library.

Output is limited to root/dist. Existing, unrelated dist data is protected:
the script refuses to replace a directory without its own marker.
"""
from __future__ import annotations

import json
import shutil
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DIST = (ROOT / "dist").resolve()
MARKER = ".arduino-3d-viet-generated"
FILES = [
    "index.html",
    "site.webmanifest",
    "sw.js",
    "styles/app.css",
    "src/app.js",
    "src/lessons.js",
    "src/simulator.js",
    "src/storage.js",
    "src/scene3d.js",
    "assets/favicon.svg",
    "assets/vendor/three.module.min.js",
    "assets/vendor/three.core.min.js",
    "assets/vendor/THREE-LICENSE.txt",
    "docs/HUONG_DAN.md",
]


def build() -> Path:
    if DIST.parent != ROOT.resolve() or DIST == ROOT.resolve():
        raise RuntimeError("Unsafe dist output path")
    if DIST.exists() and not (DIST / MARKER).is_file():
        raise RuntimeError("Refusing to replace dist without generated marker")
    for filename in FILES:
        source = ROOT / filename
        if not source.is_file() or source.resolve().is_relative_to(DIST):
            raise FileNotFoundError(f"Missing or unsafe file: {filename}")
    with tempfile.TemporaryDirectory(prefix=".arduino-site-", dir=ROOT) as temp:
        stage = Path(temp)
        for filename in FILES:
            dest = stage / filename
            dest.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(ROOT / filename, dest)
        (stage / MARKER).write_text("Generated by scripts/build_site.py\n", encoding="utf-8")
        if DIST.exists():
            shutil.rmtree(DIST)
        shutil.copytree(stage, DIST)
    manifest = json.loads((DIST / "site.webmanifest").read_text(encoding="utf-8"))
    if manifest.get("lang") != "vi":
        raise RuntimeError("Expected Vietnamese manifest")
    return DIST


if __name__ == "__main__":
    try:
        output = build()
    except Exception as exc:
        print(f"Build failed: {exc}", file=sys.stderr)
        sys.exit(1)
    print(f"OK: static website exported to {output}")
