"""Create a deterministic, fail-closed local release backup.

This utility is intentionally local-only. It reads source bytes from one exact
Git commit, validates a release-site build and the bundled firmware, then writes
three archives plus receipts below ROOT/releases/<version-date>.

It does not tag, push, publish, deploy, install software, enumerate sources/
history, or copy the dirty working tree into the source archive.
"""
