class BackupError(ValueError):
    """Input, provenance or containment violation."""


@dataclass(frozen=True)
class GitEntry:
    path: str
    object_id: str
    executable: bool


@dataclass(frozen=True)
class BackupResult:
    directory: Path
    source_zip: Path
    dist_zip: Path
    firmware_zip: Path
    metadata: Path
    sha256sums: Path
    head_sha: str


def _sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _is_reparse_or_symlink(path: Path) -> bool:
    try:
        metadata = os.lstat(path)
    except OSError as error:
        raise BackupError(f"Không đọc được metadata an toàn: {path}") from error
    if stat.S_ISLNK(metadata.st_mode):
        return True
    attributes = getattr(metadata, "st_file_attributes", 0)
    reparse_flag = getattr(stat, "FILE_ATTRIBUTE_REPARSE_POINT", 0x400)
    return bool(attributes & reparse_flag)


def _safe_archive_name(name: str) -> str:
    if not isinstance(name, str) or not name or "\x00" in name or "\\" in name or ":" in name:
        raise BackupError(f"Đường dẫn archive không an toàn: {name!r}")
    pure = PurePosixPath(name)
    if pure.is_absolute() or any(part in {"", ".", ".."} for part in pure.parts):
        raise BackupError(f"Đường dẫn archive traversal/absolute bị từ chối: {name!r}")
    normalized = pure.as_posix()
    lower = normalized.lower()
    if any(lower == prefix[:-1] or lower.startswith(prefix) for prefix in FORBIDDEN_PREFIXES):
        raise BackupError(f"Đường dẫn bị cấm trong backup: {name}")
    if any(part.lower() == ".git" for part in pure.parts):
        raise BackupError(f"Nested .git bị cấm trong backup: {name}")
    basename = pure.name.lower()
    if (
        basename in SENSITIVE_BASENAMES
        or basename.startswith(".env.")
        or any(
            basename == prefix
            or basename.startswith(prefix + ".")
            or basename.startswith(prefix + "-")
            or basename.startswith(prefix + "_")
            for prefix in SENSITIVE_PREFIXES
        )
        or PurePosixPath(basename).suffix in SENSITIVE_SUFFIXES
        or any(part.lower() == ".ssh" for part in pure.parts)
    ):
        raise BackupError(f"Tệp có tên nhạy cảm bị từ chối: {name}")
    return normalized


def _run_git(repo_root: Path, args: list[str], *, text: bool = False) -> bytes | str:
    command = ["git", "-C", str(repo_root), *args]
    result = subprocess.run(
        command,
        capture_output=True,
        text=text,
        encoding="utf-8" if text else None,
        errors="strict" if text else None,
        timeout=20,
        check=False,
    )
    if result.returncode != 0:
        stderr = result.stderr.strip() if text else result.stderr.decode("utf-8", "replace").strip()
        raise BackupError(f"Git thất bại ({' '.join(args[:3])}): {stderr or 'không có stderr'}")
    return result.stdout


def _repo_root(path: Path) -> Path:
    requested = path.absolute()
    if not requested.is_dir() or _is_reparse_or_symlink(requested):
        raise BackupError("Repo root phải là thư mục thật, không phải symlink/reparse.")
    try:
        resolved = requested.resolve(strict=True)
    except OSError as error:
        raise BackupError("Không resolve được repo root.") from error
    observed = str(_run_git(resolved, ["rev-parse", "--show-toplevel"], text=True)).strip()
    try:
        observed_path = Path(observed).resolve(strict=True)
    except OSError as error:
        raise BackupError("Git top-level không resolve được.") from error
    if observed_path != resolved:
        raise BackupError("repo_root phải đúng Git top-level.")
    return resolved


def _pinned_head(repo_root: Path, expected: str) -> str:
    if not HEAD_RE.fullmatch(expected):
        raise BackupError("--head phải là full 40-hex commit SHA chữ thường.")
    current = str(_run_git(repo_root, ["rev-parse", "--verify", "HEAD^{commit}"], text=True)).strip()
    if current != expected:
        raise BackupError(f"HEAD hiện tại {current} không khớp SHA được pin {expected}.")
    return current


def _git_is_ancestor(repo_root: Path, ancestor: str, descendant: str) -> bool:
    if not HEAD_RE.fullmatch(ancestor) or not HEAD_RE.fullmatch(descendant):
        return False
    result = subprocess.run(
        ["git", "-C", str(repo_root), "merge-base", "--is-ancestor", ancestor, descendant],
        capture_output=True,
        timeout=20,
        check=False,
    )
    return result.returncode == 0


def collect_source_entries(repo_root: Path, head_sha: str) -> list[GitEntry]:
    """List only fixed repository-owned pathspecs from the pinned Git tree."""
    root_listing = _run_git(
        repo_root,
        ["ls-tree", "-z", "--name-only", head_sha],
        text=False,
    )
    assert isinstance(root_listing, bytes)
    allowed_roots = {PurePosixPath(path).parts[0] for path in SOURCE_PATHS}
    excluded_roots = {prefix[:-1] for prefix in FORBIDDEN_PREFIXES}
    for raw_name in root_listing.split(b"\x00"):
        if not raw_name:
            continue
        try:
            root_name = raw_name.decode("utf-8", "strict")
        except UnicodeError as error:
            raise BackupError("Git root tree có tên không phải UTF-8.") from error
        if root_name in excluded_roots:
            continue
        _safe_archive_name(root_name)
        if root_name not in allowed_roots:
            raise BackupError(
                f"HEAD có top-level tracked path chưa được allowlist review: {root_name}"
            )
    raw = _run_git(
        repo_root,
        ["ls-tree", "-r", "-z", "--full-tree", head_sha, "--", *SOURCE_PATHS],
        text=False,
    )
    assert isinstance(raw, bytes)
    entries: list[GitEntry] = []
    seen: set[str] = set()
    for record in raw.split(b"\x00"):
        if not record:
            continue
        try:
            header, raw_path = record.split(b"\t", 1)
            mode, object_type, object_id = header.decode("ascii").split(" ", 2)
            path = raw_path.decode("utf-8", "strict")
        except (ValueError, UnicodeError) as error:
            raise BackupError("Git tree chứa entry không thể giải mã an toàn.") from error
        path = _safe_archive_name(path)
        if object_type != "blob" or mode not in {"100644", "100755"}:
            raise BackupError(
                f"Chỉ regular tracked file được phép; entry bị từ chối: {path} ({mode} {object_type})"
            )
        if path in seen:
            raise BackupError(f"Git tree có path trùng: {path}")
        seen.add(path)
        entries.append(GitEntry(path=path, object_id=object_id, executable=mode == "100755"))
    missing = SOURCE_REQUIRED - seen
    if missing:
        raise BackupError(f"HEAD thiếu source bắt buộc: {sorted(missing)}")
    return sorted(entries, key=lambda item: item.path)


def read_source_blobs(repo_root: Path, entries: Iterable[GitEntry]) -> dict[str, bytes]:
    result: dict[str, bytes] = {}
    total = 0
    for entry in entries:
        blob = _run_git(repo_root, ["cat-file", "blob", entry.object_id], text=False)
        assert isinstance(blob, bytes)
        if len(blob) > MAX_FILE_BYTES:
            raise BackupError(f"Tracked file vượt giới hạn backup: {entry.path}")
        total += len(blob)
        if total > MAX_TOTAL_INPUT_BYTES:
            raise BackupError("Source tree vượt tổng giới hạn backup.")
        result[entry.path] = blob
    return result


def source_archive_entries(entries: Iterable[GitEntry]) -> list[GitEntry]:
    """Keep verification blobs available while excluding upstream source snapshots."""
    return [
        entry
        for entry in entries
        if not entry.path.startswith(UPSTREAM_SOURCE_SNAPSHOT_PREFIX)
    ]


def _resolve_input_under_root(repo_root: Path, supplied: Path, *, want_dir: bool) -> Path:
    candidate = supplied if supplied.is_absolute() else repo_root / supplied
    candidate = candidate.absolute()
    if not candidate.exists():
        raise BackupError(f"Input không tồn tại: {supplied}")

    # Walk the lexical parent chain using filesystem identity instead of string
    # comparison. Windows may expose the same path once as an 8.3 short name and
    # once as a long name; samefile() handles that without resolving away a
    # symlink/junction component that we still need to reject.
    chain: list[Path] = []
    cursor = candidate
    while True:
        try:
            if os.path.samefile(cursor, repo_root):
                break
        except OSError as error:
            raise BackupError(f"Không xác minh được input ancestor: {cursor}") from error
        chain.append(cursor)
        parent = cursor.parent
        if parent == cursor:
            raise BackupError(f"Input phải nằm trong repo root: {supplied}")
        cursor = parent
    for component in reversed(chain):
        if _is_reparse_or_symlink(component):
            raise BackupError(f"Input đi qua symlink/reparse: {component}")

    try:
        resolved = candidate.resolve(strict=True)
    except OSError as error:
        raise BackupError(f"Không resolve được input: {supplied}") from error
    if not resolved.is_relative_to(repo_root):
        raise BackupError(f"Input phải nằm trong repo root: {supplied}")
    if want_dir != resolved.is_dir():
        kind = "thư mục" if want_dir else "tệp"
        raise BackupError(f"Input phải là {kind}: {supplied}")
    return resolved


def _walk_regular_files(directory: Path) -> dict[str, bytes]:
    if _is_reparse_or_symlink(directory):
        raise BackupError(f"Không đọc directory symlink/reparse: {directory}")
    root = directory.resolve(strict=True)
    files: dict[str, bytes] = {}
    total = 0

    def visit(folder: Path) -> None:
        nonlocal total
        with os.scandir(folder) as scan:
            entries = sorted(scan, key=lambda entry: entry.name)
        for entry in entries:
            path = Path(entry.path)
            if _is_reparse_or_symlink(path):
                raise BackupError(f"Symlink/reparse bị từ chối: {path}")
            relative_name = path.relative_to(root).as_posix()
            _safe_archive_name(relative_name)
            if entry.is_dir(follow_symlinks=False):
                visit(path)
                continue
            if not entry.is_file(follow_symlinks=False):
                raise BackupError(f"Special file bị từ chối: {path}")
            resolved = path.resolve(strict=True)
            if not resolved.is_relative_to(root):
                raise BackupError(f"File thoát khỏi input root: {path}")
            name = relative_name
            data = path.read_bytes()
            if len(data) > MAX_FILE_BYTES:
                raise BackupError(f"Input file vượt giới hạn: {name}")
            total += len(data)
            if total > MAX_TOTAL_INPUT_BYTES:
                raise BackupError("Input directory vượt tổng giới hạn.")
            files[name] = data

    visit(root)
    return files


def _zip_files(archive_bytes: bytes) -> dict[str, bytes]:
    if len(archive_bytes) > MAX_ARCHIVE_BYTES:
        raise BackupError("ZIP artifact vượt giới hạn kích thước.")
    files: dict[str, bytes] = {}
    total = 0
    try:
        with ZipFile(io.BytesIO(archive_bytes), "r") as archive:
            for info in archive.infolist():
                raw_name = info.filename[:-1] if info.is_dir() and info.filename.endswith("/") else info.filename
                name = _safe_archive_name(raw_name)
                unix_mode = (info.external_attr >> 16) & 0xFFFF
                if unix_mode and stat.S_ISLNK(unix_mode):
                    raise BackupError(f"ZIP symlink bị từ chối: {name}")
                if info.flag_bits & 0x1:
                    raise BackupError(f"ZIP encrypted entry bị từ chối: {name}")
                if info.is_dir():
                    continue
                if name in files:
                    raise BackupError(f"ZIP chứa entry trùng: {name}")
                if info.file_size > MAX_FILE_BYTES:
                    raise BackupError(f"ZIP entry vượt giới hạn: {name}")
                total += info.file_size
                if total > MAX_TOTAL_INPUT_BYTES:
                    raise BackupError("ZIP uncompressed vượt tổng giới hạn.")
                files[name] = archive.read(info)
    except BackupError:
        raise
    except Exception as error:
        raise BackupError("Không đọc được ZIP artifact an toàn.") from error
    return files


def _tree_sha256(files: Mapping[str, bytes]) -> str:
    digest = hashlib.sha256()
    for name in sorted(files):
        encoded = name.encode("utf-8")
        data = files[name]
        digest.update(len(encoded).to_bytes(4, "big"))
        digest.update(encoded)
        digest.update(len(data).to_bytes(8, "big"))
        digest.update(data)
    return digest.hexdigest()


def _service_worker_assets(sw_bytes: bytes) -> list[str]:
    try:
        text = sw_bytes.decode("utf-8", "strict")
    except UnicodeError as error:
        raise BackupError("sw.js không phải UTF-8 hợp lệ.") from error
    match = SW_ASSETS_RE.search(text)
    if not match:
        raise BackupError("sw.js thiếu ASSETS declaration.")
    assets = re.findall(r'"([^"]+)"', match.group(1))
    if not assets or assets[0] != "./" or len(assets) != len(set(assets)):
        raise BackupError("sw.js ASSETS không đúng contract.")
    for asset in assets[1:]:
        if not asset.startswith("./"):
            raise BackupError(f"sw.js asset không project-relative: {asset}")
        _safe_archive_name(asset[2:])
    return assets


def _expected_built_sw(source_sw: bytes, dist_files: Mapping[str, bytes], asset_names: list[str]) -> bytes:
    try:
        source_text = source_sw.decode("utf-8", "strict").replace("\r\n", "\n").replace("\r", "\n")
    except UnicodeError as error:
        raise BackupError("Source sw.js không phải UTF-8.") from error
    digest = hashlib.sha256()
    for name in sorted(asset_names):
        if name == "sw.js":
            continue
        if name not in dist_files:
            raise BackupError(f"Dist thiếu asset dùng để content-address cache: {name}")
        digest.update(name.encode("utf-8"))
        digest.update(b"\x00")
        digest.update(dist_files[name])
    cache_id = f"arduino3d-viet-static-{digest.hexdigest()[:16]}"
    patched, count = CACHE_RE.subn(f'const CACHE = "{cache_id}";', source_text, count=1)
    if count != 1:
        raise BackupError("Source sw.js thiếu CACHE declaration chuẩn.")
    return patched.encode("utf-8")


def validate_dist_files(files: Mapping[str, bytes], source_blobs: Mapping[str, bytes]) -> None:
    if files.get(BUILD_MARKER) != BUILD_MARKER_BYTES:
        raise BackupError("Dist thiếu marker hợp lệ của scripts/build_site.py.")
    for required in (
        "index.html",
        "site.webmanifest",
        "sw.js",
        "src/lessons.js",
        "assets/firmware/manifest.json",
    ):
        if required not in files:
            raise BackupError(f"Dist thiếu file bắt buộc: {required}")
    assets = _service_worker_assets(files["sw.js"])
    asset_names = [asset[2:] for asset in assets[1:]]
    expected_files = {BUILD_MARKER, "sw.js", *asset_names}
    if set(files) != expected_files:
        missing = sorted(expected_files - set(files))
        extra = sorted(set(files) - expected_files)
        raise BackupError(f"Dist không khớp service-worker allowlist; thiếu={missing}, dư={extra}")
    for name in asset_names:
        if name not in source_blobs:
            raise BackupError(f"Dist asset không tồn tại trong pinned HEAD source: {name}")
        if files[name] != source_blobs[name]:
            raise BackupError(f"Dist asset khác pinned HEAD: {name}")
    expected_sw = _expected_built_sw(source_blobs["sw.js"], files, ["sw.js", *asset_names])
    if files["sw.js"] != expected_sw:
        raise BackupError("Dist sw.js không đúng deterministic build của pinned HEAD.")


def _validate_manifest_sha(value: object, label: str) -> str:
    if not isinstance(value, str) or not SHA256_RE.fullmatch(value):
        raise BackupError(f"Firmware manifest {label} không phải SHA-256 hợp lệ.")
    return value


def _extract_pinned_sketches(source_bytes: bytes):
    """Use the owning sketch extractor on the pinned HEAD lesson bytes."""
    with tempfile.TemporaryDirectory(prefix="arduino3d-safe-backup-lessons-") as temp:
        source_path = Path(temp) / "lessons.js"
        source_path.write_bytes(source_bytes)
        try:
            return verify_sketches.extract_sketches(source_path)
        except (OSError, UnicodeError, ValueError) as error:
            raise BackupError(
                "Pinned src/lessons.js không qua được owning Sketch parser."
            ) from error


def validate_firmware_files(
    files: Mapping[str, bytes],
    source_blobs: Mapping[str, bytes],
    repo_root: Path,
    head_sha: str,
) -> dict:
    expected_names = {"manifest.json", *[f"lesson_{index:02d}.hex" for index in range(1, 17)]}
    if set(files) != expected_names:
        raise BackupError(
            f"Firmware bundle phải có đúng manifest + 16 HEX; "
            f"thiếu={sorted(expected_names - set(files))}, dư={sorted(set(files) - expected_names)}"
        )
    for name in sorted(expected_names):
        tracked = f"assets/firmware/{name}"
        if source_blobs.get(tracked) != files[name]:
            raise BackupError(f"Firmware input khác pinned HEAD: {tracked}")
    try:
        manifest = json.loads(files["manifest.json"].decode("utf-8", "strict"))
    except (UnicodeError, json.JSONDecodeError) as error:
        raise BackupError("Firmware manifest không phải JSON UTF-8 hợp lệ.") from error
    if (
        not isinstance(manifest, dict)
        or manifest.get("schema_version") != 1
        or manifest.get("format") != "arduino-uno-intel-hex"
        or manifest.get("board") != verify_sketches.FQBN
        or manifest.get("source_file") != "src/lessons.js"
    ):
        raise BackupError("Firmware manifest sai schema/board/source contract.")
    manifest_git_sha = manifest.get("git_sha")
    if not isinstance(manifest_git_sha, str) or not HEAD_RE.fullmatch(manifest_git_sha):
        raise BackupError("Firmware manifest git_sha không hợp lệ.")
    if not _git_is_ancestor(repo_root, manifest_git_sha, head_sha):
        raise BackupError("Firmware manifest git_sha không phải ancestor của pinned HEAD.")
    source_sha = _validate_manifest_sha(manifest.get("source_sha256"), "source_sha256")
    if source_sha != _sha256(source_blobs["src/lessons.js"]):
        raise BackupError("Firmware source_sha256 khác src/lessons.js tại pinned HEAD.")
    expected_toolchain = {
        "arduino_cli": export_firmware.EXPECTED_CLI,
        "arduino_avr_core": export_firmware.EXPECTED_CORE,
        "servo_library": export_firmware.EXPECTED_SERVO,
    }
    if manifest.get("toolchain") != expected_toolchain:
        raise BackupError("Firmware manifest không đúng owning pinned toolchain.")
    source_sketches = _extract_pinned_sketches(source_blobs["src/lessons.js"])
    lessons = manifest.get("lessons")
    if not isinstance(lessons, list) or len(lessons) != 16:
        raise BackupError("Firmware manifest phải có đúng 16 lesson records.")
    for lesson_id, row in enumerate(lessons, start=1):
        filename = f"lesson_{lesson_id:02d}.hex"
        source_sketch = source_sketches[lesson_id - 1]
        if (
            not isinstance(row, dict)
            or row.get("id") != lesson_id
            or row.get("file") != filename
            or row.get("slug") != source_sketch.slug
            or not isinstance(row.get("hex_bytes"), int)
            or row["hex_bytes"] < 11
            or row["hex_bytes"] > MAX_FILE_BYTES
        ):
            raise BackupError(f"Firmware manifest row {lesson_id} không hợp lệ.")
        for key in ("hex_sha256", "flash_sha256", "sketch_sha256"):
            _validate_manifest_sha(row.get(key), f"lesson {lesson_id} {key}")
        expected_sketch_sha = export_firmware.digest(
            source_sketch.source.encode("utf-8")
        )
        if row["sketch_sha256"] != expected_sketch_sha:
            raise BackupError(
                f"Firmware lesson {lesson_id} sketch SHA/slug khác pinned lesson source."
            )
        data = files[filename]
        if len(data) != row["hex_bytes"] or _sha256(data) != row["hex_sha256"]:
            raise BackupError(f"Firmware lesson {lesson_id} bị thay đổi/tamper so với manifest.")
        try:
            text = data.decode("ascii", "strict")
        except UnicodeError as error:
            raise BackupError(f"Firmware lesson {lesson_id} không phải Intel HEX ASCII.") from error
        try:
            flash = export_firmware.parse_intel_hex(text)
        except export_firmware.FirmwareError as error:
            raise BackupError(
                f"Firmware lesson {lesson_id} không qua strict owning Intel HEX parser."
            ) from error
        if row["flash_sha256"] != export_firmware.digest(flash):
            raise BackupError(
                f"Firmware lesson {lesson_id} flash SHA khác strict parsed AVR flash."
            )
    return manifest


def _zip_bytes(files: Mapping[str, bytes], *, executable_paths: set[str] | None = None) -> bytes:
    executable_paths = executable_paths or set()
    output = io.BytesIO()
    with ZipFile(output, "w", compression=ZIP_DEFLATED, compresslevel=9) as archive:
        for name in sorted(files):
            safe_name = _safe_archive_name(name)
            info = ZipInfo(safe_name, date_time=ZIP_EPOCH)
            info.compress_type = ZIP_DEFLATED
            mode = 0o755 if safe_name in executable_paths else 0o644
            info.external_attr = mode << 16
            archive.writestr(
                info,
                files[name],
                compress_type=ZIP_DEFLATED,
                compresslevel=9,
            )
    data = output.getvalue()
    if len(data) > MAX_ARCHIVE_BYTES:
        raise BackupError("Generated ZIP vượt giới hạn kích thước.")
    return data


def _metadata_bytes(payload: dict) -> bytes:
    return (json.dumps(payload, ensure_ascii=False, indent=2, sort_keys=True) + "\n").encode("utf-8")


def create_backup(
    *,
    repo_root: Path,
    version_date: str,
    head_sha: str,
    dist_dir: Path | None = None,
    dist_artifact: Path | None = None,
    dist_artifact_sha256: str | None = None,
    firmware_dir: Path | None = None,
) -> BackupResult:
    """Validate all inputs first, then create one new local backup directory."""
    if not VERSION_RE.fullmatch(version_date):
        raise BackupError("version_date phải có dạng vN.N.N-YYYYMMDD.")
    version_core = version_date.split("-", 1)[0][1:]
    major, minor, patch = (int(part) for part in version_core.split("."))
    if (major, minor, patch) < (1, 5, 0):
        raise BackupError("Safe Backup v1.5 từ chối target legacy v1.3/v1.4.")
    try:
        datetime.strptime(version_date.rsplit("-", 1)[1], "%Y%m%d")
    except ValueError as error:
        raise BackupError("version_date chứa ngày lịch không hợp lệ.") from error
    root = _repo_root(repo_root)
    head = _pinned_head(root, head_sha)
    if (dist_dir is None) == (dist_artifact is None):
        raise BackupError("Chọn đúng một trong dist_dir hoặc dist_artifact.")
    if dist_artifact is not None:
        if not isinstance(dist_artifact_sha256, str) or not SHA256_RE.fullmatch(
            dist_artifact_sha256
        ):
            raise BackupError("dist_artifact bắt buộc có SHA-256 exact từ release gate.")
    elif dist_artifact_sha256 is not None:
        raise BackupError("dist_artifact_sha256 chỉ dùng cùng dist_artifact.")

    entries = collect_source_entries(root, head)
    pinned_head_blobs = read_source_blobs(root, entries)
    archive_entries = source_archive_entries(entries)
    source_blobs = {
        entry.path: pinned_head_blobs[entry.path]
        for entry in archive_entries
    }
    executable = {entry.path for entry in archive_entries if entry.executable}
    source_zip_bytes = _zip_bytes(source_blobs, executable_paths=executable)

    if dist_dir is not None:
        dist_path = _resolve_input_under_root(root, dist_dir, want_dir=True)
        dist_files = _walk_regular_files(dist_path)
        validate_dist_files(dist_files, pinned_head_blobs)
        dist_zip_bytes = _zip_bytes(dist_files)
        dist_mode = "verified-build-directory"
        dist_input_sha = None
    else:
        assert dist_artifact is not None and dist_artifact_sha256 is not None
        artifact_path = _resolve_input_under_root(root, dist_artifact, want_dir=False)
        artifact_bytes = artifact_path.read_bytes()
        if _sha256(artifact_bytes) != dist_artifact_sha256:
            raise BackupError("Dist artifact SHA-256 không khớp release-gate pin.")
        dist_files = _zip_files(artifact_bytes)
        validate_dist_files(dist_files, pinned_head_blobs)
        dist_zip_bytes = artifact_bytes
        dist_mode = "exact-release-gate-artifact"
        dist_input_sha = dist_artifact_sha256

    firmware_supplied = firmware_dir if firmware_dir is not None else Path("assets/firmware")
    firmware_path = _resolve_input_under_root(root, firmware_supplied, want_dir=True)
    firmware_files = _walk_regular_files(firmware_path)
    firmware_manifest = validate_firmware_files(
        firmware_files,
        pinned_head_blobs,
        root,
        head,
    )
    firmware_archive_files = {
        f"assets/firmware/{name}": data for name, data in firmware_files.items()
    }
    firmware_zip_bytes = _zip_bytes(firmware_archive_files)

    commit_time = str(
        _run_git(root, ["show", "-s", "--format=%cI", head], text=True)
    ).strip()
    prefix = "Arduino3DVietnam"
    source_name = f"{prefix}-source-{version_date}.zip"
    dist_name = f"{prefix}-dist-{version_date}.zip"
    firmware_name = f"{prefix}-firmware-{version_date}.zip"
    archives = {
        source_name: source_zip_bytes,
        dist_name: dist_zip_bytes,
        firmware_name: firmware_zip_bytes,
    }
    metadata_payload = {
        "schema_version": 1,
        "version_date": version_date,
        "head_sha": head,
        "head_commit_time": commit_time,
        "source": {
            "mode": "pinned-git-tree",
            "file_count": len(source_blobs),
            "tree_sha256": _tree_sha256(source_blobs),
            "verification_blob_count": len(pinned_head_blobs),
            "excluded_upstream_prefixes": [UPSTREAM_SOURCE_SNAPSHOT_PREFIX],
            "zip": source_name,
            "zip_sha256": _sha256(source_zip_bytes),
        },
        "dist": {
            "mode": dist_mode,
            "file_count": len(dist_files),
            "tree_sha256": _tree_sha256(dist_files),
            "input_artifact_sha256": dist_input_sha,
            "zip": dist_name,
            "zip_sha256": _sha256(dist_zip_bytes),
        },
        "firmware": {
            "mode": "pinned-head-manifest-verified",
            "file_count": len(firmware_files),
            "tree_sha256": _tree_sha256(firmware_files),
            "manifest_git_sha": firmware_manifest["git_sha"],
            "manifest_source_sha256": firmware_manifest["source_sha256"],
            "zip": firmware_name,
            "zip_sha256": _sha256(firmware_zip_bytes),
        },
    }
    metadata_name = "backup-metadata.json"
    metadata = _metadata_bytes(metadata_payload)
    receipt_files = {**archives, metadata_name: metadata}
    sums = "".join(
        f"{_sha256(receipt_files[name])}  {name}\n"
        for name in sorted(receipt_files)
    ).encode("ascii")

    releases = root / RELEASES_DIRNAME
    if releases.exists():
        if not releases.is_dir() or _is_reparse_or_symlink(releases):
            raise BackupError("releases phải là directory thật.")
    else:
        releases.mkdir(mode=0o755)
    target = releases / version_date
    if target.exists():
        raise BackupError(f"Refusing to overwrite existing backup: {target}")
    target.mkdir()
    try:
        for name, data in sorted(archives.items()):
            (target / name).write_bytes(data)
        metadata_path = target / metadata_name
        metadata_path.write_bytes(metadata)
        sums_path = target / "SHA256SUMS"
        sums_path.write_bytes(sums)
    except Exception:
        shutil.rmtree(target, ignore_errors=True)
        raise

    return BackupResult(
        directory=target,
        source_zip=target / source_name,
        dist_zip=target / dist_name,
        firmware_zip=target / firmware_name,
        metadata=target / metadata_name,
        sha256sums=target / "SHA256SUMS",
        head_sha=head,
    )


def _configure_utf8_stdio() -> None:
    for stream in (sys.stdout, sys.stderr):
        reconfigure = getattr(stream, "reconfigure", None)
        if callable(reconfigure):
            reconfigure(encoding="utf-8", errors="replace")


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description=(
            "Tạo backup local fail-closed từ pinned HEAD + verified dist + "
            "16 firmware HEX."
        )
    )
    parser.add_argument("--repo-root", type=Path, default=ROOT)
    parser.add_argument("--version-date", required=True)
    parser.add_argument(
        "--head",
        required=True,
        help="Full 40-hex SHA phải đúng HEAD hiện tại.",
    )
    dist = parser.add_mutually_exclusive_group(required=True)
    dist.add_argument(
        "--dist-dir",
        type=Path,
        help="Build directory đã qua release gate/local verification.",
    )
    dist.add_argument(
        "--dist-artifact",
        type=Path,
        help="Exact ZIP artifact từ release gate.",
    )
    parser.add_argument(
        "--dist-sha256",
        help="Bắt buộc khi dùng --dist-artifact.",
    )
    parser.add_argument(
        "--firmware-dir",
        type=Path,
        default=Path("assets/firmware"),
    )
    return parser


def main(argv: list[str] | None = None) -> int:
    _configure_utf8_stdio()
    args = build_parser().parse_args(argv)
    try:
        result = create_backup(
            repo_root=args.repo_root,
            version_date=args.version_date,
            head_sha=args.head,
            dist_dir=args.dist_dir,
            dist_artifact=args.dist_artifact,
            dist_artifact_sha256=args.dist_sha256,
            firmware_dir=args.firmware_dir,
        )
    except (BackupError, OSError, subprocess.SubprocessError) as error:
        print(f"Backup refused: {error}", file=sys.stderr)
        return 1
    print(f"OK local backup: {result.directory}")
    print(f"HEAD: {result.head_sha}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
